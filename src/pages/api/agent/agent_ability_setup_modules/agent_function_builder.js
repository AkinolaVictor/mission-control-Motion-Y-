import fs from 'fs/promises';
import path from 'path';

/**
 * Logic to generate Node.js function files for an agent.
 * @param {string} agentId - The ID of the agent.
 * @param {Array} functions - List of functions to create from the plan.
 */
export async function buildAgentFunctions(agentId, functions) {
  const functionsDir = path.join(process.cwd(), 'agents', agentId, 'functions');

  // Ensure the functions directory exists
  await fs.mkdir(functionsDir, { recursive: true });

  const results = [];

  for (const fn of functions) {
    const filePath = path.join(functionsDir, `${fn.name}.js`);

    // Basic Node.js function template
    const content = `/**
 * ${fn.description}
 * Generated by Orchestrator Onboarding
 */
export async function ${fn.name}(params) {
  console.log('Executing ${fn.name} with params:', params);

  // Logic provided by Orchestrator:
  ${fn.logic || '// Logic not specified'}

  return { success: true, data: {} };
}
`;

    await fs.writeFile(filePath, content, 'utf8');
    results.push({ name: fn.name, path: filePath });
  }

  return results;
}
